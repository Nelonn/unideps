    #[test]
    fn test_resolve_library_path() {
        let temp = tempfile::tempdir().unwrap();
        let prefix = temp.path();
        let lib_dir = prefix.join("lib");
        std::fs::create_dir_all(&lib_dir).unwrap();
        std::fs::write(lib_dir.join("yuv.lib"), b"dummy").unwrap();

        let resolved = CMakeGenerator::resolve_library_path(prefix, Path::new("lib/yuv"));
        assert_eq!(resolved, Some(lib_dir.join("yuv.lib")));

        let resolved_stem = CMakeGenerator::resolve_library_path(prefix, Path::new("yuv"));
        assert_eq!(resolved_stem, Some(lib_dir.join("yuv.lib")));

        // A library named like a directory must resolve to the file, not to `<prefix>/lib`.
        std::fs::write(lib_dir.join("liblib.a"), b"dummy").unwrap();
        let resolved_lib = CMakeGenerator::resolve_library_path(prefix, Path::new("lib"));
        assert_eq!(resolved_lib, Some(lib_dir.join("liblib.a")));
    }

