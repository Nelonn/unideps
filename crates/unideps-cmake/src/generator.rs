use std::fmt::Write;
use std::path::{Path, PathBuf};
use unideps_core::graph::DependencyNode;

pub struct CMakeGenerator;

/// Makes `value` a quoted CMake argument that means exactly the string it is, the way
/// `-D<KEY>=<VALUE>` on a configure command line does. A Windows path is the usual reason:
/// `C:\Users\Nelonn\...` inside quotes is read as the escape `\U` and fails to parse.
/// `${...}` is not expanded either, because the command line does not expand it; the
/// references unideps itself understands are already resolved by the time a value gets here.
fn quote(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    for c in value.chars() {
        match c {
            '\\' | '"' | '$' => {
                out.push('\\');
                out.push(c);
            }
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out
}

/// Emitted once, ahead of the `add_subdirectory` calls, when the manifest has a
/// `cmake-subdirectory` dependency.
const SUBDIR_HELPERS: &str = r#"
function(_unideps_has_prefix str prefix out_var)
    string(LENGTH "${prefix}" _unideps_prefix_len)
    string(LENGTH "${str}" _unideps_str_len)
    if(_unideps_str_len LESS _unideps_prefix_len)
        set(${out_var} FALSE PARENT_SCOPE)
        return()
    endif()
    string(SUBSTRING "${str}" 0 ${_unideps_prefix_len} _unideps_head)
    if(_unideps_head STREQUAL "${prefix}")
        set(${out_var} TRUE PARENT_SCOPE)
    else()
        set(${out_var} FALSE PARENT_SCOPE)
    endif()
endfunction()

# A package added with add_subdirectory defines its targets in its own directory scope and
# in those of its subdirectories, not in the scope that added it, so BUILDSYSTEM_TARGETS of
# the current directory does not see them -- hence the walk. Collects the library targets the
# package exports as `<ns>::<target>`, aliasing the ones it left unaliased, so that a
# multi-target package is linked under the same names a cmake-install build of it would give
# the consumer. Targets that are not the package's own (its vendored third-party
# subdirectories) keep to themselves: they neither carry an `<ns>::` alias nor start with
# `<ns>`, so they are left alone.
function(_unideps_subdir_exports dir ns out_var)
    set(_unideps_exports "")
    set(_unideps_pending "${dir}")
    while(_unideps_pending)
        list(POP_FRONT _unideps_pending _unideps_dir)
        get_property(_unideps_subs DIRECTORY "${_unideps_dir}" PROPERTY SUBDIRECTORIES)
        list(APPEND _unideps_pending ${_unideps_subs})
        get_property(_unideps_dir_targets DIRECTORY "${_unideps_dir}" PROPERTY BUILDSYSTEM_TARGETS)
        foreach(_unideps_t IN LISTS _unideps_dir_targets)
            get_target_property(_unideps_t_type ${_unideps_t} TYPE)
            if(_unideps_t_type STREQUAL "EXECUTABLE" OR _unideps_t_type STREQUAL "UTILITY")
                continue()
            endif()
            if(TARGET ${ns}::${_unideps_t})
                list(APPEND _unideps_exports "${ns}::${_unideps_t}")
            else()
                _unideps_has_prefix("${_unideps_t}" "${ns}" _unideps_owned)
                if(_unideps_owned)
                    add_library(${ns}::${_unideps_t} ALIAS ${_unideps_t})
                    list(APPEND _unideps_exports "${ns}::${_unideps_t}")
                endif()
            endif()
        endforeach()
    endwhile()
    if(_unideps_exports)
        list(REMOVE_DUPLICATES _unideps_exports)
        list(SORT _unideps_exports)
    endif()
    set(${out_var} "${_unideps_exports}" PARENT_SCOPE)
endfunction()
"#;

impl CMakeGenerator {
    pub fn generate_targets_cmake(nodes: &[&DependencyNode]) -> String {
        let mut out = String::new();
        writeln!(&mut out, "# Generated by UniDeps. Do not edit.").unwrap();
        // include() runs in its own policy scope, so these only affect this file.
        writeln!(&mut out, "cmake_policy(SET CMP0057 NEW)").unwrap();
        writeln!(&mut out, "if(POLICY CMP0074)\n    cmake_policy(SET CMP0074 NEW)\nendif()").unwrap();
        if nodes.iter().any(|n| n.subdir_source.is_some()) {
            // So that the `option()` calls of a package added with add_subdirectory honour the
            // values set for it below instead of resetting them to their own defaults.
            writeln!(&mut out, "set(CMAKE_POLICY_DEFAULT_CMP0077 NEW)").unwrap();
            writeln!(&mut out, "{SUBDIR_HELPERS}").unwrap();
        }
        writeln!(&mut out).unwrap();

        for node in nodes {
            if let Some(ref prefix) = node.install_prefix {
                let norm = prefix.to_string_lossy().replace('\\', "/");
                let var_name_upper = node.name.to_uppercase();
                let var_name_raw = &node.name;
                let mut vars = std::collections::BTreeSet::new();
                vars.insert(format!("UNIDEPS_{var_name_upper}_ROOT"));
                vars.insert(format!("{var_name_upper}_ROOT"));
                vars.insert(format!("{var_name_raw}_ROOT"));
                if let Some(ref imp) = node.import_name {
                    let imp_upper = imp.to_uppercase();
                    vars.insert(format!("{imp}_ROOT"));
                    vars.insert(format!("{imp_upper}_ROOT"));
                }
                for v in vars {
                    writeln!(&mut out, "set({v} \"{norm}\")").unwrap();
                }
                writeln!(&mut out, "list(PREPEND CMAKE_PREFIX_PATH \"{norm}\")").unwrap();
                writeln!(&mut out, "list(PREPEND CMAKE_MODULE_PATH \"{norm}\")").unwrap();
                writeln!(&mut out, "list(PREPEND CMAKE_FIND_ROOT_PATH \"{norm}\")").unwrap();
            }
        }
        writeln!(&mut out).unwrap();

        // Read by unideps_setup() to copy the runtime libraries next to the consumer's binaries.
        writeln!(&mut out, "set(UNIDEPS_INSTALL_PREFIXES \"\")").unwrap();
        for node in nodes {
            if let Some(ref prefix) = node.install_prefix {
                let norm = prefix.to_string_lossy().replace('\\', "/");
                writeln!(&mut out, "list(APPEND UNIDEPS_INSTALL_PREFIXES \"{norm}\")").unwrap();
            }
        }
        // find_package(CONFIG) caches the location it found in a <Pkg>_DIR PATH entry, and
        // reuses it on the next configure as long as that directory still exists -- even when
        // CMAKE_PREFIX_PATH / <Pkg>_ROOT now point somewhere else. A rebuilt dependency lands
        // in a prefix with a different hash while the old one stays on disk, so the consumer
        // would keep linking the previous build until `installed/` is wiped by hand. Drop the
        // <Pkg>_DIR entries that point into a unideps install root other than this run's
        // prefixes. CMAKE_* entries (this build's own install prefix and search paths) and
        // anything inside them are never touched.
        out.push_str(r#"set(_unideps_roots "")
set(_unideps_keep "${UNIDEPS_INSTALL_PREFIXES}")
if(CMAKE_INSTALL_PREFIX)
    list(APPEND _unideps_keep "${CMAKE_INSTALL_PREFIX}")
endif()
foreach(_unideps_p IN LISTS _unideps_keep)
    get_filename_component(_unideps_r "${_unideps_p}" DIRECTORY)
    list(APPEND _unideps_roots "${_unideps_r}")
endforeach()
if(_unideps_roots)
    list(REMOVE_DUPLICATES _unideps_roots)
    get_cmake_property(_unideps_cache_vars CACHE_VARIABLES)
    foreach(_unideps_v IN LISTS _unideps_cache_vars)
        if(NOT _unideps_v MATCHES "_DIR$" OR _unideps_v MATCHES "^(CMAKE_|UNIDEPS_|_)")
            continue()
        endif()
        string(REPLACE "\\" "/" _unideps_val "${${_unideps_v}}")
        set(_unideps_stale FALSE)
        foreach(_unideps_r IN LISTS _unideps_roots)
            string(FIND "${_unideps_val}" "${_unideps_r}/" _unideps_pos)
            if(_unideps_pos EQUAL 0)
                set(_unideps_stale TRUE)
            endif()
        endforeach()
        foreach(_unideps_p IN LISTS _unideps_keep)
            string(FIND "${_unideps_val}" "${_unideps_p}/" _unideps_pos)
            if(_unideps_pos EQUAL 0 OR _unideps_val STREQUAL "${_unideps_p}")
                set(_unideps_stale FALSE)
            endif()
        endforeach()
        if(_unideps_stale)
            message(STATUS "UniDeps: dropping stale cache entry ${_unideps_v}=${_unideps_val}")
            unset(${_unideps_v} CACHE)
        endif()
    endforeach()
endif()
"#);
        writeln!(&mut out).unwrap();

        for node in nodes {
            if let Some(ref prefix) = node.install_prefix {
                let norm = prefix.to_string_lossy().replace('\\', "/");
                let name = &node.name;
                let explicit_import = node.import_name.as_deref();
                let target_name = format!("{name}::{name}");
                let ver_opt = node.tag.as_deref()
                    .or_else(|| node.commit.as_deref().map(|c| if c.len() >= 7 { &c[..7] } else { c }))
                    .or(node.branch.as_deref())
                    .or(node.version.as_deref());

                let should_auto_import =
                    node.auto_import || node.header_only || !node.include_dirs.is_empty() || !node.libraries.is_empty();

                if should_auto_import {
                    writeln!(&mut out, "if(NOT TARGET {target_name} AND NOT TARGET {name})").unwrap();

                    let mut inc_paths = Vec::new();
                    for inc in &node.include_dirs {
                        let full_path = if inc.is_absolute() {
                            inc.clone()
                        } else {
                            prefix.join(inc)
                        };
                        inc_paths.push(full_path.to_string_lossy().replace('\\', "/"));
                    }

                    let is_shared = node.shared.unwrap_or(node.config.shared);
                    let mut lib_paths: Vec<String> = Vec::new();
                    let mut unresolved: Vec<String> = Vec::new();
                    for lib in &node.libraries {
                        match Self::resolve_library_path(prefix, lib) {
                            Some(resolved) => lib_paths.push(resolved.to_string_lossy().replace('\\', "/")),
                            None => unresolved.push(lib.to_string_lossy().replace('\\', "/")),
                        }
                    }
                    let mut dll: Option<String> = node.binaries.first().map(|bin| {
                        let full = if bin.is_absolute() { bin.clone() } else { prefix.join(bin) };
                        full.to_string_lossy().replace('\\', "/")
                    });
                    if lib_paths.is_empty() && !node.header_only {
                        let (found_lib, found_dll) = Self::find_library_file(prefix, name, is_shared);
                        if let Some(l) = found_lib {
                            lib_paths.push(l.replace('\\', "/"));
                            if dll.is_none() {
                                dll = found_dll.map(|d| d.replace('\\', "/"));
                            }
                        }
                    } else if is_shared && dll.is_none() && let Some(first) = lib_paths.first() {
                        dll = Self::find_dll_for(prefix, Path::new(first));
                    }
                    for u in &unresolved {
                        writeln!(&mut out, "    message(WARNING \"UniDeps: library '{u}' of '{name}' not found in {norm}\")").unwrap();
                    }

                    let main_lib = if node.header_only { None } else { lib_paths.first().cloned() };
                    match main_lib {
                        None => {
                            if !node.header_only {
                                writeln!(&mut out, "    message(WARNING \"UniDeps: no library found for '{name}' in {norm}; importing it as header-only\")").unwrap();
                            }
                            writeln!(&mut out, "    add_library({target_name} INTERFACE IMPORTED)").unwrap();
                        }
                        Some(ref lib) => {
                            let is_dll_import = is_shared
                                && dll.as_deref().is_some_and(|d| d.to_lowercase().ends_with(".dll"));
                            if is_dll_import {
                                let dll_path = dll.as_deref().unwrap_or_default();
                                writeln!(&mut out, "    add_library({target_name} SHARED IMPORTED)").unwrap();
                                writeln!(&mut out, "    set_target_properties({target_name} PROPERTIES IMPORTED_LOCATION \"{dll_path}\" IMPORTED_IMPLIB \"{lib}\")").unwrap();
                            } else {
                                writeln!(&mut out, "    add_library({target_name} UNKNOWN IMPORTED)").unwrap();
                                writeln!(&mut out, "    set_target_properties({target_name} PROPERTIES IMPORTED_LOCATION \"{lib}\")").unwrap();
                            }
                            if lib_paths.len() > 1 {
                                let extra = lib_paths[1..].join(";");
                                writeln!(&mut out, "    set_property(TARGET {target_name} APPEND PROPERTY INTERFACE_LINK_LIBRARIES \"{extra}\")").unwrap();
                            }
                        }
                    }

                    if inc_paths.is_empty() {
                        let default_inc = format!("{norm}/include");
                        writeln!(&mut out, "    if(EXISTS \"{default_inc}\")").unwrap();
                        writeln!(&mut out, "        set_target_properties({target_name} PROPERTIES INTERFACE_INCLUDE_DIRECTORIES \"{default_inc}\")").unwrap();
                        writeln!(&mut out, "    endif()").unwrap();
                    } else {
                        let inc_joined = inc_paths.join(";");
                        writeln!(&mut out, "    set_target_properties({target_name} PROPERTIES INTERFACE_INCLUDE_DIRECTORIES \"{inc_joined}\")").unwrap();
                    }
                    writeln!(&mut out, "endif()").unwrap();

                    if let Some(imp) = explicit_import {
                        writeln!(&mut out, "if(NOT TARGET {imp}::{imp} AND TARGET {target_name})").unwrap();
                        writeln!(&mut out, "    add_library({imp}::{imp} INTERFACE IMPORTED)").unwrap();
                        writeln!(&mut out, "    target_link_libraries({imp}::{imp} INTERFACE {target_name})").unwrap();
                        writeln!(&mut out, "endif()").unwrap();
                        if imp != name {
                            writeln!(&mut out, "if(NOT TARGET {imp} AND TARGET {target_name})").unwrap();
                            writeln!(&mut out, "    add_library({imp} INTERFACE IMPORTED)").unwrap();
                            writeln!(&mut out, "    target_link_libraries({imp} INTERFACE {target_name})").unwrap();
                            writeln!(&mut out, "endif()").unwrap();
                        }
                    }
                    writeln!(&mut out, "if(NOT TARGET {name} AND TARGET {target_name})").unwrap();
                    writeln!(&mut out, "    add_library({name} INTERFACE IMPORTED)").unwrap();
                    writeln!(&mut out, "    target_link_libraries({name} INTERFACE {target_name})").unwrap();
                    writeln!(&mut out, "endif()").unwrap();

                    if !node.dependencies.is_empty() {
                        writeln!(&mut out, "if(TARGET {target_name})").unwrap();
                        for dep in &node.dependencies {
                            let dep_node = nodes.iter().find(|n| n.name == *dep);
                            let dep_import = dep_node.and_then(|n| n.import_name.as_deref());
                            if let Some(imp) = dep_import {
                                writeln!(&mut out, "    if(TARGET {imp}::{imp})").unwrap();
                                writeln!(&mut out, "        target_link_libraries({target_name} INTERFACE {imp}::{imp})").unwrap();
                                writeln!(&mut out, "    elseif(TARGET {imp})").unwrap();
                                writeln!(&mut out, "        target_link_libraries({target_name} INTERFACE {imp})").unwrap();
                                writeln!(&mut out, "    elseif(TARGET {dep}::{dep})").unwrap();
                                writeln!(&mut out, "        target_link_libraries({target_name} INTERFACE {dep}::{dep})").unwrap();
                                writeln!(&mut out, "    elseif(TARGET {dep})").unwrap();
                                writeln!(&mut out, "        target_link_libraries({target_name} INTERFACE {dep})").unwrap();
                                writeln!(&mut out, "    endif()").unwrap();
                            } else {
                                writeln!(&mut out, "    if(TARGET {dep}::{dep})").unwrap();
                                writeln!(&mut out, "        target_link_libraries({target_name} INTERFACE {dep}::{dep})").unwrap();
                                writeln!(&mut out, "    elseif(TARGET {dep})").unwrap();
                                writeln!(&mut out, "        target_link_libraries({target_name} INTERFACE {dep})").unwrap();
                                writeln!(&mut out, "    endif()").unwrap();
                            }
                        }
                        writeln!(&mut out, "endif()").unwrap();
                    }

                    let display_name = explicit_import.unwrap_or(name);
                    let targets = if let Some(imp) = explicit_import {
                        if imp == name {
                            target_name.clone()
                        } else {
                            format!("{target_name};{imp}::{imp}")
                        }
                    } else {
                        target_name.clone()
                    };
                    let ver_str = ver_opt.map(|v| format!(" (version {v})")).unwrap_or_default();
                    writeln!(&mut out, "message(STATUS \"Imported: {display_name} ({targets}) ({norm}){ver_str}\")").unwrap();
                } else {
                    let initial_pkg = explicit_import.unwrap_or(name);
                    writeln!(&mut out, "set(_unideps_{name}_imported_pkg \"{initial_pkg}\")").unwrap();
                    if let Some(ver) = ver_opt {
                        writeln!(&mut out, "set(_unideps_{name}_ver \"{}\")", quote(ver)).unwrap();
                    } else {
                        writeln!(&mut out, "set(_unideps_{name}_ver \"\")").unwrap();
                    }

                    writeln!(&mut out, "if(CMAKE_VERSION VERSION_GREATER_EQUAL 3.21)").unwrap();
                    writeln!(&mut out, "    get_property(_unideps_{name}_targets_before DIRECTORY PROPERTY IMPORTED_TARGETS)").unwrap();
                    writeln!(&mut out, "endif()").unwrap();

                    let mut attempted_packages = Vec::new();
                    if let Some(imp) = explicit_import {
                        attempted_packages.push(imp.to_string());
                    } else {
                        attempted_packages.extend(Self::find_cmake_configs(prefix));
                        if attempted_packages.is_empty() {
                            attempted_packages.push(name.to_string());
                        }
                    }

                    let found_var = format!("_unideps_{name}_found");
                    writeln!(&mut out, "set({found_var} FALSE)").unwrap();

                    // Restricted to CMAKE_PREFIX_PATH / <Pkg>_ROOT (set above for this node) so a
                    // same-named package already installed on the system is never picked up in
                    // place of the one unideps just built -- that would silently defeat version
                    // pinning instead of failing loudly.
                    for pkg in &attempted_packages {
                        let pkg_upper = pkg.to_uppercase();
                        writeln!(&mut out, "if(NOT {found_var})").unwrap();
                        writeln!(&mut out, "    find_package({pkg} CONFIG QUIET NO_CMAKE_ENVIRONMENT_PATH NO_SYSTEM_ENVIRONMENT_PATH NO_CMAKE_PACKAGE_REGISTRY NO_CMAKE_SYSTEM_PATH NO_SYSTEM_PACKAGE_REGISTRY)").unwrap();
                        writeln!(&mut out, "    if({pkg}_FOUND OR {pkg_upper}_FOUND)").unwrap();
                        writeln!(&mut out, "        set({found_var} TRUE)").unwrap();
                        writeln!(&mut out, "        set(_unideps_{name}_imported_pkg \"{pkg}\")").unwrap();
                        writeln!(&mut out, "    endif()").unwrap();
                        writeln!(&mut out, "endif()").unwrap();
                    }

                    writeln!(&mut out, "if(NOT {found_var})").unwrap();
                    writeln!(&mut out, "    message(FATAL_ERROR \"UniDeps: could not resolve dependency '{name}' via find_package CONFIG in {norm}\")").unwrap();
                    writeln!(&mut out, "endif()").unwrap();

                    writeln!(&mut out, "set(_unideps_{name}_new_targets \"\")").unwrap();
                    writeln!(&mut out, "if(CMAKE_VERSION VERSION_GREATER_EQUAL 3.21)").unwrap();
                    writeln!(&mut out, "    get_property(_unideps_{name}_targets_after DIRECTORY PROPERTY IMPORTED_TARGETS)").unwrap();
                    writeln!(&mut out, "    foreach(_t IN LISTS _unideps_{name}_targets_after)").unwrap();
                    writeln!(&mut out, "        if(NOT _t IN_LIST _unideps_{name}_targets_before)").unwrap();
                    writeln!(&mut out, "            list(APPEND _unideps_{name}_new_targets \"${{_t}}\")").unwrap();
                    writeln!(&mut out, "        endif()").unwrap();
                    writeln!(&mut out, "    endforeach()").unwrap();
                    writeln!(&mut out, "endif()").unwrap();

                    writeln!(&mut out, "if(NOT _unideps_{name}_new_targets)").unwrap();
                    writeln!(&mut out, "    if(TARGET {name}::{name})").unwrap();
                    writeln!(&mut out, "        set(_unideps_{name}_new_targets \"{name}::{name}\")").unwrap();
                    writeln!(&mut out, "    elseif(TARGET ${{_unideps_{name}_imported_pkg}}::${{_unideps_{name}_imported_pkg}})").unwrap();
                    writeln!(&mut out, "        set(_unideps_{name}_new_targets \"${{_unideps_{name}_imported_pkg}}::${{_unideps_{name}_imported_pkg}}\")").unwrap();
                    writeln!(&mut out, "    elseif(TARGET {name})").unwrap();
                    writeln!(&mut out, "        set(_unideps_{name}_new_targets \"{name}\")").unwrap();
                    writeln!(&mut out, "    elseif(TARGET ${{_unideps_{name}_imported_pkg}})").unwrap();
                    writeln!(&mut out, "        set(_unideps_{name}_new_targets \"${{_unideps_{name}_imported_pkg}}\")").unwrap();
                    writeln!(&mut out, "    else()").unwrap();
                    writeln!(&mut out, "        set(_unideps_{name}_new_targets \"${{_unideps_{name}_imported_pkg}}\")").unwrap();
                    writeln!(&mut out, "    endif()").unwrap();
                    writeln!(&mut out, "endif()").unwrap();

                    writeln!(&mut out, "if(NOT _unideps_{name}_ver)").unwrap();
                    writeln!(&mut out, "    string(TOUPPER \"${{_unideps_{name}_imported_pkg}}\" _unideps_{name}_imported_pkg_upper)").unwrap();
                    writeln!(&mut out, "    if(DEFINED ${{_unideps_{name}_imported_pkg}}_VERSION AND NOT \"${{${{_unideps_{name}_imported_pkg}}_VERSION}}\" STREQUAL \"\")").unwrap();
                    writeln!(&mut out, "        set(_unideps_{name}_ver \"${{${{_unideps_{name}_imported_pkg}}_VERSION}}\")").unwrap();
                    writeln!(&mut out, "    elseif(DEFINED ${{_unideps_{name}_imported_pkg_upper}}_VERSION AND NOT \"${{${{_unideps_{name}_imported_pkg_upper}}_VERSION}}\" STREQUAL \"\")").unwrap();
                    writeln!(&mut out, "        set(_unideps_{name}_ver \"${{${{_unideps_{name}_imported_pkg_upper}}_VERSION}}\")").unwrap();
                    writeln!(&mut out, "    endif()").unwrap();
                    writeln!(&mut out, "endif()").unwrap();

                    writeln!(&mut out, "set(_unideps_{name}_ver_str \"\")").unwrap();
                    writeln!(&mut out, "if(_unideps_{name}_ver)").unwrap();
                    writeln!(&mut out, "    set(_unideps_{name}_ver_str \" (version ${{_unideps_{name}_ver}})\")").unwrap();
                    writeln!(&mut out, "endif()").unwrap();

                    writeln!(&mut out, "message(STATUS \"Imported: ${{_unideps_{name}_imported_pkg}} (${{_unideps_{name}_new_targets}}) ({norm})${{_unideps_{name}_ver_str}}\")").unwrap();
                }
            } else if node.subdir_source.is_some() {
                Self::write_subdirectory(&mut out, node);
            }
        }

        writeln!(&mut out).unwrap();
        out
    }

    /// `cmake-subdirectory`: the consumer builds the package itself, from the sources
    /// unideps prepared. Emitted in the same dependency order as everything else, so a
    /// subdirectory package that another one uses is added first.
    fn write_subdirectory(out: &mut String, node: &DependencyNode) {
        let Some(ref src) = node.subdir_source else { return };
        let src = src.to_string_lossy().replace('\\', "/");
        let name = &node.name;

        // The package reads this instead of running unideps again: its own `unideps.toml`
        // was already resolved and built by the run that generated this file.
        let mut set_before: Vec<(String, String)> = Vec::new();
        if let Some(ref file) = node.subdir_nested_targets {
            set_before.push((
                "UNIDEPS_NESTED_TARGETS".into(),
                file.to_string_lossy().replace('\\', "/"),
            ));
        }
        if let Some(shared) = node.shared {
            set_before.push(("BUILD_SHARED_LIBS".into(), if shared { "ON".into() } else { "OFF".into() }));
        }
        // Already resolved by the run that prepared the sources, so that `${<dep>.prefix}`
        // means here exactly what it means on the configure command line of a normal build.
        for (k, v) in &node.subdir_options {
            set_before.push((k.clone(), v.clone()));
        }

        // Set by the block below once the sources have been added, so that a second
        // include of this file -- or another project in the same build tree depending on
        // the same package -- does not add the same source directory twice.
        writeln!(out, "get_property(_unideps_{name}_subdir_added GLOBAL PROPERTY _unideps_subdir_{name})").unwrap();
        writeln!(out, "if(NOT _unideps_{name}_subdir_added AND NOT TARGET {name} AND NOT TARGET {name}::{name})").unwrap();
        // The values belong to this package's configure, not to the rest of the consumer's,
        // so whatever the consumer had is put back afterwards.
        for (k, v) in &set_before {
            writeln!(out, "    set(_unideps_had_{k} FALSE)").unwrap();
            writeln!(out, "    if(DEFINED {k})").unwrap();
            writeln!(out, "        set(_unideps_had_{k} TRUE)").unwrap();
            writeln!(out, "        set(_unideps_save_{k} \"${{{k}}}\")").unwrap();
            writeln!(out, "    endif()").unwrap();
            writeln!(out, "    set({k} \"{}\")", quote(v)).unwrap();
        }
        writeln!(
            out,
            "    add_subdirectory(\"{src}\" \"${{CMAKE_CURRENT_BINARY_DIR}}/_unideps/{name}\")"
        )
        .unwrap();
        for (k, _) in set_before.iter().rev() {
            writeln!(out, "    if(_unideps_had_{k})").unwrap();
            writeln!(out, "        set({k} \"${{_unideps_save_{k}}}\")").unwrap();
            writeln!(out, "    else()").unwrap();
            writeln!(out, "        unset({k})").unwrap();
            writeln!(out, "    endif()").unwrap();
        }
        writeln!(out, "    set_property(GLOBAL PROPERTY _unideps_subdir_{name} TRUE)").unwrap();
        writeln!(out, "    set(_unideps_{name}_subdir_added TRUE)").unwrap();
        writeln!(out, "endif()").unwrap();

        // The package names its own targets; `<name>::<name>` is what the consumer expects,
        // so alias it when only the plain name came out of the subdirectory.
        let mut aliases: Vec<String> = vec![format!("{name}::{name}")];
        if let Some(ref imp) = node.import_name {
            aliases.push(format!("{imp}::{imp}"));
            if imp != name {
                aliases.push(imp.clone());
            }
        }
        for alias in &aliases {
            writeln!(out, "if(TARGET {name} AND NOT TARGET {alias})").unwrap();
            writeln!(out, "    get_target_property(_unideps_{name}_type {name} TYPE)").unwrap();
            writeln!(out, "    if(NOT _unideps_{name}_type STREQUAL \"EXECUTABLE\" AND NOT _unideps_{name}_type STREQUAL \"UTILITY\")").unwrap();
            writeln!(out, "        add_library({alias} ALIAS {name})").unwrap();
            writeln!(out, "    endif()").unwrap();
            writeln!(out, "endif()").unwrap();
        }

        // A package that is more than one library -- `<name>_core`, `<name>_engine`, ... --
        // has no target called `<name>` to alias, and is linked under the names it exports
        // itself. Those are what the consumer wants reported, so look them up; the
        // directory properties they come from only exist for sources this file added.
        let mut namespaces: Vec<&str> = vec![name.as_str()];
        if let Some(ref imp) = node.import_name
            && imp != name
        {
            namespaces.push(imp.as_str());
        }
        writeln!(out, "set(_unideps_{name}_exports \"\")").unwrap();
        writeln!(out, "if(_unideps_{name}_subdir_added)").unwrap();
        for ns in &namespaces {
            writeln!(out, "    _unideps_subdir_exports(\"{src}\" \"{ns}\" _unideps_{name}_{ns}_exports)").unwrap();
            writeln!(out, "    list(APPEND _unideps_{name}_exports ${{_unideps_{name}_{ns}_exports}})").unwrap();
        }
        writeln!(out, "endif()").unwrap();

        let expected = aliases.first().cloned().unwrap_or_default();
        writeln!(out, "if(TARGET {expected})").unwrap();
        writeln!(out, "    message(STATUS \"Subdirectory: {name} ({expected}) ({src})\")").unwrap();
        writeln!(out, "elseif(TARGET {name})").unwrap();
        writeln!(out, "    message(STATUS \"Subdirectory: {name} ({name}) ({src})\")").unwrap();
        writeln!(out, "elseif(_unideps_{name}_exports)").unwrap();
        writeln!(out, "    string(REPLACE \";\" \", \" _unideps_{name}_exports_str \"${{_unideps_{name}_exports}}\")").unwrap();
        writeln!(out, "    message(STATUS \"Subdirectory: {name} (${{_unideps_{name}_exports_str}}) ({src})\")").unwrap();
        writeln!(out, "else()").unwrap();
        writeln!(out, "    message(WARNING \"UniDeps: {src} defines no target called '{name}' and none under '{name}::'; link against whatever its CMakeLists.txt does define\")").unwrap();
        writeln!(out, "endif()").unwrap();
    }

    fn find_cmake_configs(prefix: &Path) -> Vec<String> {
        let mut configs = Vec::new();
        let search_dirs = [
            prefix.join("lib").join("cmake"),
            prefix.join("cmake"),
            prefix.join("share"),
            prefix.to_path_buf(),
        ];

        for dir in &search_dirs {
            if dir.exists() {
                for entry in walkdir::WalkDir::new(dir).max_depth(5).into_iter().filter_map(|e| e.ok()) {
                    let fname = entry.file_name().to_string_lossy();
                    if let Some(pkg) = fname.strip_suffix("Config.cmake").or_else(|| fname.strip_suffix("-config.cmake"))
                        && !pkg.is_empty() && !configs.contains(&pkg.to_string()) {
                            configs.push(pkg.to_string());
                        }
                }
            }
        }
        configs
    }

    pub fn resolve_library_path(prefix: &Path, lib_hint: &Path) -> Option<PathBuf> {
        if lib_hint.is_absolute() && lib_hint.is_file() {
            return Some(lib_hint.to_path_buf());
        }

        let direct = prefix.join(lib_hint);
        if direct.is_file() {
            return Some(direct);
        }

        let raw_name = lib_hint.file_name()?.to_string_lossy();
        let stem = lib_hint
            .file_stem()
            .map(|s| s.to_string_lossy().to_string())
            .unwrap_or_else(|| raw_name.to_string());
        let clean_stem = stem.strip_prefix("lib").unwrap_or(&stem);

        let search_dirs = [
            if let Some(parent) = lib_hint.parent() {
                if !parent.as_os_str().is_empty() {
                    prefix.join(parent)
                } else {
                    prefix.join("lib")
                }
            } else {
                prefix.join("lib")
            },
            prefix.join("lib"),
            prefix.to_path_buf(),
        ];

        let candidates = [
            format!("{clean_stem}.lib"),
            format!("lib{clean_stem}.a"),
            format!("lib{clean_stem}.so"),
            format!("lib{clean_stem}.dylib"),
            format!("lib{clean_stem}.lib"),
            format!("{clean_stem}.a"),
            format!("{clean_stem}.so"),
            format!("{clean_stem}.dylib"),
            format!("{clean_stem}.dll.a"),
            format!("{stem}.lib"),
            format!("lib{stem}.a"),
            format!("lib{stem}.so"),
            format!("lib{stem}.dylib"),
            format!("{stem}.a"),
            format!("{stem}.so"),
            format!("{stem}.dylib"),
        ];

        for dir in &search_dirs {
            if dir.exists() {
                for cand in &candidates {
                    let candidate_path = dir.join(cand);
                    if candidate_path.is_file() {
                        return Some(candidate_path);
                    }
                }
            }
        }

        None
    }

    fn find_dll_for(prefix: &Path, lib: &Path) -> Option<String> {
        let stem = lib.file_stem()?.to_string_lossy().to_string();
        let clean_stem = stem.strip_prefix("lib").unwrap_or(&stem).to_string();
        let bin_dir = prefix.join("bin");
        [format!("{clean_stem}.dll"), format!("lib{clean_stem}.dll"), format!("{stem}.dll")]
            .into_iter()
            .map(|c| bin_dir.join(c))
            .find(|p| p.exists())
            .map(|p| p.to_string_lossy().replace('\\', "/"))
    }

    fn find_library_file(prefix: &Path, name: &str, shared: bool) -> (Option<String>, Option<String>) {
        let lib_dir = prefix.join("lib");
        let bin_dir = prefix.join("bin");

        if !lib_dir.exists() {
            return (None, None);
        }

        let clean_name = name.strip_prefix("lib").unwrap_or(name).to_lowercase();
        let name_lower = name.to_lowercase();

        let mut named_static = None;
        let mut named_implib = None;
        let mut fallback_static = None;
        let mut fallback_implib = None;

        if let Ok(entries) = std::fs::read_dir(&lib_dir) {
            for entry in entries.flatten() {
                let path = entry.path();
                let fname = path.file_name().unwrap_or_default().to_string_lossy();
                let fname_lower = fname.to_lowercase();

                let is_match = fname_lower.contains(&clean_name) || fname_lower.contains(&name_lower);

                if fname_lower.ends_with("static.lib") || fname_lower.ends_with(".a") {
                    if is_match && named_static.is_none() {
                        named_static = Some(path.to_string_lossy().to_string());
                    } else if fallback_static.is_none() {
                        fallback_static = Some(path.to_string_lossy().to_string());
                    }
                } else if fname_lower.ends_with(".lib")
                    || fname_lower.ends_with(".so")
                    || fname_lower.contains(".so.")
                    || fname_lower.ends_with(".dylib")
                {
                    if is_match && named_implib.is_none() {
                        named_implib = Some(path.to_string_lossy().to_string());
                    } else if fallback_implib.is_none() {
                        fallback_implib = Some(path.to_string_lossy().to_string());
                    }
                }
            }
        }

        let static_lib = named_static.or(fallback_static);
        let implib = named_implib.or(fallback_implib);

        if !shared && static_lib.is_some() {
            return (static_lib, None);
        }

        let mut dll_path = None;
        if bin_dir.exists()
            && let Ok(entries) = std::fs::read_dir(&bin_dir) {
                for entry in entries.flatten() {
                    let path = entry.path();
                    let fname = path.file_name().unwrap_or_default().to_string_lossy();
                    let fname_lower = fname.to_lowercase();
                    if fname_lower.ends_with(".dll") || fname_lower.ends_with(".so") || fname_lower.contains(".so.") || fname_lower.ends_with(".dylib") {
                        if fname_lower.contains(&clean_name) || fname_lower.contains(&name_lower) {
                            dll_path = Some(path.to_string_lossy().to_string());
                            break;
                        } else if dll_path.is_none() {
                            dll_path = Some(path.to_string_lossy().to_string());
                        }
                    }
                }
            }

        if shared && implib.is_some() {
            (implib, dll_path)
        } else if static_lib.is_some() {
            (static_lib, None)
        } else {
            (implib, dll_path)
        }
    }
}

